def make_combined_figure(metric: str, ylabel: str, stem: str):
    set_paper_style()
    fig, axes = plt.subplots(2, 3, figsize=(13.0, 6.6), sharey="row")

    col_order = ["Celebrities", "Objects", "Styles"]
    row_order = [("dual", "Dual blocks"), ("single", "Single blocks")]

    for c, dataset_name in enumerate(col_order):
        df = DATASETS[dataset_name]
        for r, (kind, row_title) in enumerate(row_order):
            ax = axes[r, c]
            d = df[df["kind"] == kind].sort_values("block_index")
            x = d["block_index"].tolist()
            y = d[metric].tolist()

            title = dataset_name if r == 0 else ""
            plot_curve(
                ax=ax,
                x=x,
                y=y,
                title=title,
                xlabel="Block index",
                ylabel=ylabel if c == 0 else "",
            )

    fig.tight_layout()
    save_fig(fig, stem)


def make_per_dataset_figures(metric: str, ylabel: str, stem_suffix: str):
    set_paper_style()

    for dataset_name, df in DATASETS.items():
        fig, axes = plt.subplots(1, 2, figsize=(9.2, 3.4))

        for ax, kind, title in zip(
            axes,
            ["dual", "single"],
            ["Dual blocks", "Single blocks"]
        ):
            d = df[df["kind"] == kind].sort_values("block_index")
            x = d["block_index"].tolist()
            y = d[metric].tolist()
            plot_curve(
                ax=ax,
                x=x,
                y=y,
                title=title,
                xlabel="Block index",
                ylabel=ylabel,
            )

        fig.suptitle(dataset_name, y=1.02)
        fig.tight_layout()
        safe_name = dataset_name.lower().replace(" ", "_")
        save_fig(fig, f"{safe_name}_{stem_suffix}")


